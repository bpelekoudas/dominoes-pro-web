const BY_ID = new Map(CATALOG.map((item) => [item.id, item]));
const BY_AVATAR = new Map(CATALOG.filter((item) => item.avatarId).map((item) => [item.avatarId as string, item]));

/** Ids that must never be sold, equipped, or granted. */
const WITHHELD = new Set(["CHR-015", "2hot4tv"]);

export function isWithheldId(value: string | null | undefined): boolean {
  if (!value) return false;
  return WITHHELD.has(value.trim());
}

export function itemById(id: string | null | undefined): StoreItem | null {
  if (!id || isWithheldId(id)) return null;
  return BY_ID.get(id) ?? null;
}

export function characterItem(avatarId: string | null | undefined): StoreItem | null {
  if (!avatarId || isWithheldId(avatarId)) return null;
  return BY_AVATAR.get(avatarId) ?? null;
}

export function canBuy(item: StoreItem, currency: StoreCurrency): boolean {
  if (item.limited) return false;
  if (item.obtain === "bones") {
    if (currency === "bones") return (item.bones ?? 0) > 0;
    return (item.gold ?? 0) > 0;
  }
  if (item.obtain === "gold") return currency === "gold" && (item.gold ?? 0) > 0;
  return false;
}

export function priceOf(item: StoreItem, currency: StoreCurrency): number | null {
  if (!canBuy(item, currency)) return null;
  return currency === "bones" ? item.bones : item.gold;
}
